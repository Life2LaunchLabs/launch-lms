/** The label as people read it, without its emoji ("Vocational Training"); the stored value when it isn't one of ours. */
export function orgLabelText(value?: string | null): string {
  if (!value) return ''
  const found = ORG_LABELS.find((item) => item.value === value)
  return found ? found.label.replace(/^\S+\s/, '') : value
}
