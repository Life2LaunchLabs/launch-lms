/* global process, URL, __dirname, document, innerWidth, console */
// Run against the local, synthetic 20-member / three-pilot scenario fixture.
const { chromium, expect } = require('@playwright/test');
const fs = require('fs');
const path = require('path');
const base = process.env.DEMO_BROWSER_BASE_URL || 'http://127.0.0.1:13100';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw Error('Synthetic local fixtures only');
const out = path.resolve(__dirname, '../../../docs/plans/active/demo-checkpoints/evidence');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const findings = [];
  const publicContext = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await publicContext.newPage();
  await page.goto(base + '/demo');
  await expect(page.locator('[data-testid^="demo-account-"]')).toHaveCount(3, { timeout: 60000 });
  await expect(page.getByRole('heading', { name: 'Casey Admin', exact: true })).toBeVisible();
  const published = await (await publicContext.request.get(base + '/api/demo/status')).json();
  if (published.accounts.some(account => account.email || account.user_email)) throw Error('Public email leaked');
  await page.getByTestId('demo-account-3').getByRole('button', { name: 'Start demo', exact: true }).click();
  await page.getByRole('button', { name: 'Reset', exact: true }).waitFor({ timeout: 90000 });
  const selected = await (await publicContext.request.get(base + '/api/demo/status')).json();
  if (selected.pilot_user_id !== 3) throw Error('Wrong pilot');
  const programsUrl = base + '/api/v1/programs/';
  const listed = await publicContext.request.get(programsUrl + '?org_id=2');
  if (!listed.ok()) throw Error('Org-admin program access ' + listed.status() + await listed.text());
  const programs = await listed.json();
  if (!JSON.stringify(programs).includes('Your next chapter')) throw Error('Program omitted');
  const roster = await publicContext.request.get(base + '/api/v1/orgs/2/users?limit=100');
  if (!roster.ok()) throw Error('Admin cohort unavailable ' + roster.status());
  const people = await roster.json();
  if (!JSON.stringify(people).includes('Learner 21') || JSON.stringify(people).includes('operator@example.com')) throw Error('Cohort missing or real user exposed');
  const stages = [];
  for (const identifier of [2, 4, 6]) {
    const matrix = await publicContext.request.get(programsUrl + 'assignments/assignment_fixture_' + identifier + '/matrix?org_id=2');
    if (!matrix.ok()) throw Error('Assignment matrix unavailable ' + matrix.status());
    const data = await matrix.json();
    const serialized = JSON.stringify(data);
    const expected = ['not_started', 'in_progress', 'completed'][identifier % 3];
    if (!serialized.includes(expected)) throw Error('Prepared progress omitted: ' + expected);
    stages.push(expected);
  }
  const edited = await publicContext.request.put(programsUrl + 'program_fixture?org_id=2', { data: { name: 'Private admin edit' } });
  if (!edited.ok()) throw Error('Org-admin edit ' + edited.status() + await edited.text());
  await page.goto(base + '/orgs/demo-scenario/admin/programs');
  await expect(page.getByText('Private admin edit', { exact: true }).first()).toBeVisible({ timeout: 60000 });
  await expect(page.getByText('Platform', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Reset', exact: true }).waitFor();
  await page.screenshot({ path: out + '/org-admin-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: out + '/org-admin-phone.png', fullPage: true });
  const token = (await publicContext.cookies()).find(cookie => cookie.name === 'access_token_cookie').value;
  await page.getByRole('button', { name: 'Back to demo users', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Back to demo users', exact: true }).click();
  await page.getByTestId('demo-account-4').getByRole('button', { name: 'Start demo', exact: true }).waitFor({ timeout: 60000 });
  const revoked = await publicContext.request.get(base + '/api/v1/users/session', { headers: { Authorization: 'Bearer ' + token } });
  if (revoked.status() !== 401) throw Error('Back did not revoke admin pilot');
  await page.getByTestId('demo-account-4').getByRole('button', { name: 'Start demo', exact: true }).click();
  await page.getByRole('button', { name: 'Reset', exact: true }).waitFor({ timeout: 90000 });
  const learner = await (await publicContext.request.get(base + '/api/demo/status')).json();
  if (learner.pilot_user_id !== 4 || learner.checkpoint_id !== selected.checkpoint_id) throw Error('Selection did not share checkpoint');
  const forbidden = await publicContext.request.put(programsUrl + 'program_fixture?org_id=2', { data: { name: 'Forbidden edit' } });
  if (forbidden.status() !== 403) throw Error('Learner gained admin edit ' + forbidden.status());
  const details = await publicContext.request.get(programsUrl + 'me/all/details');
  if (!details.ok() || !JSON.stringify(await details.json()).includes('Your next chapter')) throw Error('Learner program missing');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Reset demo', exact: true }).click();
  await page.getByRole('button', { name: 'Reset', exact: true }).waitFor({ timeout: 90000 });
  const reset = await (await publicContext.request.get(base + '/api/demo/status')).json();
  if (reset.pilot_user_id !== 4) throw Error('Reset switched pilot');
  await publicContext.request.post(base + '/api/demo/end', { headers: { Origin: base } });
  findings.push({ publicPilots: 3, sameCheckpoint: selected.checkpoint_id, cohortRoster: 'fake identities preserved; real operator absent', preparedStages: stages, platformNavigation: 'absent', orgAdminEdit: edited.status(), learnerEdit: forbidden.status(), backRevocation: revoked.status(), resetPilot: reset.pilot_user_id });
  await publicContext.close();

  const admin = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const setup = await admin.newPage();
  await setup.goto(base + '/login');
  await setup.getByLabel('Email address').fill('operator@example.com');
  await setup.getByLabel('Password').fill('demo-fixture-only');
  await setup.getByRole('button', { name: /log ?in|sign ?in/i }).click();
  await setup.waitForURL(url => !url.pathname.includes('login'), { timeout: 90000 });
  await setup.goto(base + '/demo');
  await expect(setup.locator('[data-testid^="demo-account-"]')).toHaveCount(20, { timeout: 60000 });
  await setup.getByRole('button', { name: 'Manage demo accounts', exact: true }).click();
  await expect(setup.getByRole('switch')).toHaveCount(20);
  await setup.screenshot({ path: out + '/cohort-manager-desktop.png' });
  await setup.setViewportSize({ width: 390, height: 844 });
  if (await setup.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Manager phone overflow');
  await setup.screenshot({ path: out + '/cohort-manager-phone.png' });
  await setup.getByRole('button', { name: 'Save cohort', exact: true }).click();
  await expect(setup.getByRole('status').filter({ hasText: 'Cohort saved.' })).toBeVisible();
  await setup.getByRole('button', { name: 'Close account management', exact: true }).click();
  // A nonpilot cohort member is still editable through the normal live app.
  await setup.getByTestId('demo-account-5').getByRole('button', { name: 'Edit live account', exact: true }).click();
  await setup.getByRole('button', { name: 'Save checkpoint', exact: true }).waitFor({ timeout: 60000 });
  await setup.getByRole('button', { name: 'Switch demo user', exact: true }).click();
  await setup.getByTestId('demo-account-3').getByRole('button', { name: 'Edit live account', exact: true }).waitFor({ timeout: 60000 });
  // The live program was never touched by the disposable admin edit.
  const live = await admin.request.get(programsUrl + '?org_id=2');
  if (!live.ok() || JSON.stringify(await live.json()).includes('Private admin edit')) throw Error('Demo edit reached live source');
  findings.push({ cohortMembers: 20, managerSave: 'passed', nonpilotLiveEditing: 'passed', sourceUnchanged: 'passed', phoneOverflow: false });
  await admin.close();
  fs.writeFileSync(out + '/cohort-browser-results.json', JSON.stringify(findings, null, 2));
  process.stdout.write(JSON.stringify(findings) + '\n');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
